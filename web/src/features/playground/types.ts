// Message types
export type MessageRole = 'user' | 'assistant' | 'system'

export type MessageStatus = 'loading' | 'streaming' | 'complete' | 'error'

export type PlaygroundMessageLayoutMode = 'alternating' | 'left'

export interface MessageVersion {
  id: string
  content: string
}

export interface Message {
  key: string
  from: MessageRole
  versions: MessageVersion[]
  createdAt?: number
  startedAt?: number
  completedAt?: number
  durationMs?: number
  sources?: { href: string; title: string }[]
  reasoning?: {
    content: string
    duration: number
    startedAt?: number
    completedAt?: number
    durationMs?: number
  }
  isReasoningStreaming?: boolean
  isReasoningComplete?: boolean
  isContentComplete?: boolean
  status?: MessageStatus
  errorCode?: string | null
  /**
   * 实际服务本次请求的成员（响应头 X-Served-By，ui-spec §6.8）。
   *
   * 流式/非流式都会在响应头里回传，值为 channel=<id>:<name>, model=<upstream>；
   * 缺失（旧上游/直连）时 undefined，展示层据此不渲染。
   */
  servedBy?: string
}

// API payload types
export interface ChatCompletionMessage {
  role: MessageRole
  content: string | ContentPart[]
}

export interface ContentPart {
  type: 'text' | 'image_url'
  text?: string
  image_url?: {
    url: string
  }
}

export interface ChatCompletionRequest {
  model: string
  messages: ChatCompletionMessage[]
  stream: boolean
  temperature?: number
  top_p?: number
  max_tokens?: number
  frequency_penalty?: number
  presence_penalty?: number
  seed?: number
}

export interface ChatCompletionChunk {
  id: string
  object: string
  created: number
  model: string
  choices: Array<{
    index: number
    delta: {
      role?: MessageRole
      content?: string
      reasoning_content?: string
    }
    finish_reason: string | null
  }>
}

export interface ChatCompletionResponse {
  id: string
  object: string
  created: number
  model: string
  choices: Array<{
    index: number
    message: {
      role: MessageRole
      content: string
      reasoning_content?: string
    }
    finish_reason: string
  }>
  usage?: {
    prompt_tokens: number
    completion_tokens: number
    total_tokens: number
  }
}

/**
 * 非流式调用的返回：响应体 + 实际命中的上游（X-Served-By，可能缺失）。
 */
export interface ChatCompletionResult {
  response: ChatCompletionResponse
  servedBy?: string
}

// Configuration types
export interface PlaygroundConfig {
  model: string
  /**
   * 客户端密钥（模型面凭据 `pbr-...`）。
   *
   * 试打台本质上是一个"下游客户端"：必须像下游一样带客户端密钥打
   * `/v1/chat/completions`，管理面会话 Cookie 对模型面无效（token-spec §1）。
   * 仅保存在本机 localStorage，可在令牌页轮换。
   */
  clientKey: string
  temperature: number
  top_p: number
  max_tokens: number
  frequency_penalty: number
  presence_penalty: number
  seed: number | null
  stream: boolean
}

export interface ParameterEnabled {
  temperature: boolean
  top_p: boolean
  max_tokens: boolean
  frequency_penalty: boolean
  presence_penalty: boolean
  seed: boolean
}

// Model options
export interface ModelOption {
  label: string
  value: string
}
