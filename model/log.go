// estimateRequestCost 折算一次请求的上游花费（人民币）与命中的峰谷时段下标。
//
// 单价：只按**渠道级上游单价**（channel.Setting.pbr_prices）折算；渠道未配价
// （含 channelId<=0 或渠道缓存 miss）→ 不折算（0），band 按兜底 -1 记录。没有
// 全局默认单价表（design-v1 §16.9#7：单用户自用每渠道自己定价即可）。
// **计价键 = 成员所选模型名（渠道 × 模型，2026-10-25 起）**：单价表的 key 按该
// 渠道声明/成员所选的模型名匹配，与流量从哪条车道进来无关——同一渠道一份价、
// 服务多少条车道都生效（旧口径按请求模型名/车道名匹配，多车道部署下永不命中，
// 成本恒 0）。调用方传入的 priceModel 已按"所选模型 > 请求模型 > 改写后模型名"
// 的回退链解析。usageSemantic 决定缓存是否从 prompt 中扣减（见
// pricing_setting.EstimateWithPrice：openai/gemini 扣，anthropic 不扣）。
//
// 峰谷：按**请求开始时间 at** 在价格行的 timezone 下匹配第一条命中的 band，
// 未命中用行级价兜底（design-v1 §16.9#7）。
func estimateRequestCost(channelId int, priceModel string, at time.Time, prompt, completion, cacheRead, cacheWrite int, usageSemantic string) (float64, int) {
	if channelId <= 0 {
		return 0, pricing_setting.FallbackPriceBand
	}
	priceModel = strings.TrimSpace(priceModel)
	channel, err := CacheGetChannel(channelId)
	if err != nil || channel == nil {
		return 0, pricing_setting.FallbackPriceBand
	}
	for _, item := range channel.GetSetting().PBRPrices {
		if strings.TrimSpace(item.Model) != priceModel {
			continue
		}
		return pricing_setting.EstimateWithPriceAt(priceToModelPrice(item), at,
			prompt, completion, cacheRead, cacheWrite, usageSemantic)
	}
	return 0, pricing_setting.FallbackPriceBand
}

// priceToModelPrice 把渠道价格契约（dto）映射为折算算术输入。峰谷 band 的可选
// 价格字段用指针保留"未填 → 继承行级兜底价"语义。
func priceToModelPrice(item dto.ChannelModelPrice) pricing_setting.ModelPrice {
	price := pricing_setting.ModelPrice{
		Model:      item.Model,
		Input:      item.Input,
		Output:     item.Output,
		CacheRead:  item.CacheRead,
		CacheWrite: item.CacheWrite,
		Timezone:   item.Timezone,
	}
	if len(item.Bands) == 0 {
		return price
	}
	bands := make([]pricing_setting.PriceBand, 0, len(item.Bands))
	for _, band := range item.Bands {
		bands = append(bands, pricing_setting.PriceBand{
			Days:       band.Days,
			Start:      band.Start,
			End:        band.End,
			Input:      band.Input,
			Output:     band.Output,
			CacheRead:  band.CacheRead,
			CacheWrite: band.CacheWrite,
		})
	}
	price.Bands = bands
	return price
}

func RecordConsumeLog(c *gin.Context, userId int, params RecordConsumeLogParams) {
	// PBR 元数据日志：把 token 用量与折算金额回填到请求载体，
	// 由转发收尾统一落库（design-v1 §8：日志只存元数据，成本只折算）。
	if carrier := GetPBRLogCarrier(c); carrier != nil {
		// 上游用量语义必须随日志落库：缓存折算公式按它区分
		// openai（prompt 含 cache）/ anthropic（prompt 不含 cache）/ gemini。
		// 只用于算价、不落库会让以后接 Anthropic/Gemini 上游时成本按错语义折算。
		carrier.UsageSemantic = params.UsageSemantic
		if carrier.Usage == nil {
			// 折算按 PBR 单价表（design-v1 §16.9#7：人民币/百万 token，未配置则不折算）。
			// 计价键回退链（渠道 × 模型，2026-10-25 起）：成员所选模型（carrier.MemberModel，
			// 选路注入）> 请求模型名（渠道测试等无成员路径）> 改写后的模型名。
			priceModel := params.ModelName
			if carrier.MemberModel != "" {
				priceModel = carrier.MemberModel
			} else if carrier.RequestModel != "" {
				priceModel = carrier.RequestModel
			}
			// 峰谷按**请求开始时间**匹配：入站时 EnsurePBRLogCarrier 已把开始时刻
			// 写进载体（同一时刻也供首字耗时使用），这里直接消费，不再取 time.Now()
			// ——否则长请求会按收尾时刻落到错误的时段。
			startedAt := time.UnixMilli(carrier.StartedAtMs)
			if carrier.StartedAtMs <= 0 {
				startedAt = time.Now()
			}
			cost, priceBand := estimateRequestCost(params.ChannelId, priceModel, startedAt,
				params.PromptTokens, params.CompletionTokens,
				params.CacheReadTokens, params.CacheWriteTokens,
				params.UsageSemantic)
			carrier.Usage = &PBRTokenUsage{
				PromptTokens:     params.PromptTokens,
				CompletionTokens: params.CompletionTokens,
				CacheReadTokens:  params.CacheReadTokens,
				CacheWriteTokens: params.CacheWriteTokens,
				ReasoningTokens:  params.ReasoningTokens,
				IsStream:         params.IsStream,
				TotalMs:          int64(params.UseTimeSeconds) * 1000,
				EstimatedCost:    cost,
				PriceBand:        &priceBand,
			}
		}
		// 统一日志表（design-v1 §8）：模型面请求只写 request_logs（转发收尾落库），
		// 不再写基座 logs——同一请求不再记两遍。
		return
	}
	// 无载体（遗留路径）：仍写基座 logs 兼容。
	if !common.LogConsumeEnabled {
		return
	}
	logger.LogInfo(c, fmt.Sprintf("record consume log: userId=%d, params=%s", userId, common.GetJsonString(params)))
	username := c.GetString("username")
	requestId := c.GetString(common.RequestIdKey)
	upstreamRequestId := c.GetString(common.UpstreamRequestIdKey)
	createdAt := common.GetTimestamp()
	otherStr := params.Other.JSONString()
	// 判断是否需要记录 IP
	needRecordIp := false
	if settingMap, err := GetUserSetting(userId, false); err == nil {
		if settingMap.RecordIpLog {
			needRecordIp = true
		}
	}
	log := &Log{
		UserId:           userId,
		Username:         username,
		CreatedAt:        createdAt,
		Type:             LogTypeConsume,
		Content:          params.Content,
		PromptTokens:     params.PromptTokens,
		CompletionTokens: params.CompletionTokens,
		TokenName:        params.TokenName,
		ModelName:        params.ModelName,
		ChannelId:        params.ChannelId,
		TokenId:          params.TokenId,
		UseTime:          params.UseTimeSeconds,
		IsStream:         params.IsStream,
		Group:            params.Group,
		Ip: func() string {
			if needRecordIp {
				return c.ClientIP()
			}
			return ""
		}(),
		RequestId:         requestId,
		UpstreamRequestId: upstreamRequestId,
		Other:             otherStr,
	}
	err := createLog(log)
	if err != nil {
		logger.LogError(c, "failed to record log: "+err.Error())
	}
}

func GetAllLogs(logType int, startTimestamp int64, endTimestamp int64, modelName string, username string, tokenName string, startIdx int, num int, channel int, group string, requestId string, upstreamRequestId string) (logs []*Log, total int64, err error) {
	var tx *gorm.DB
	if logType == LogTypeUnknown {
		tx = LOG_DB
	} else {
		tx = LOG_DB.Where("logs.type = ?", logType)
	}

	if tx, err = applyExplicitLogTextFilter(tx, "logs.model_name", modelName); err != nil {
		return nil, 0, err
	}
	if tx, err = applyExplicitLogTextFilter(tx, "logs.username", username); err != nil {
		return nil, 0, err
	}
	if tokenName != "" {
		tx = tx.Where("logs.token_name = ?", tokenName)
	}
	if requestId != "" {
		tx = tx.Where("logs.request_id = ?", requestId)
	}
	if upstreamRequestId != "" {
		tx = tx.Where("logs.upstream_request_id = ?", upstreamRequestId)
	}
	if startTimestamp != 0 {
		tx = tx.Where("logs.created_at >= ?", startTimestamp)
	}
	if endTimestamp != 0 {
		tx = tx.Where("logs.created_at <= ?", endTimestamp)
	}
	if channel != 0 {
		tx = tx.Where("logs.channel_id = ?", channel)
	}
	if group != "" {
		tx = tx.Where("logs."+logGroupCol+" = ?", group)
	}
	err = tx.Model(&Log{}).Count(&total).Error
	if err != nil {
		return nil, 0, err
	}
	order := "logs.created_at desc, logs.id desc"
	if common.UsingLogDatabase(common.DatabaseTypeClickHouse) {
		order = clickHouseLogOrder("logs.")
	}
	err = tx.Order(order).Limit(num).Offset(startIdx).Find(&logs).Error
	if err != nil {
		return nil, 0, err
	}
	if common.UsingLogDatabase(common.DatabaseTypeClickHouse) {
		assignDisplayLogIds(logs, startIdx)
	}

	channelIds := types.NewSet[int]()
	for _, log := range logs {
		if log.ChannelId != 0 {
			channelIds.Add(log.ChannelId)
		}
	}

	if channelIds.Len() > 0 {
		var channels []struct {
			Id   int    `gorm:"column:id"`
			Name string `gorm:"column:name"`
		}
		if common.MemoryCacheEnabled {
			// Cache get channel
			for _, channelId := range channelIds.Items() {
				if cacheChannel, err := CacheGetChannel(channelId); err == nil {
					channels = append(channels, struct {
						Id   int    `gorm:"column:id"`
						Name string `gorm:"column:name"`
					}{
						Id:   channelId,
						Name: cacheChannel.Name,
					})
				}
			}
		} else {
			// Bulk query channels from DB
			if err = DB.Table("channels").Select("id, name").Where("id IN ?", channelIds.Items()).Find(&channels).Error; err != nil {
				return logs, total, err
			}
		}
		channelMap := make(map[int]string, len(channels))
		for _, channel := range channels {
			channelMap[channel.Id] = channel.Name
		}
		for i := range logs {
			logs[i].ChannelName = channelMap[logs[i].ChannelId]
		}
	}

	return logs, total, err
}

const logSearchCountLimit = 10000

func GetUserLogs(userId int, logType int, startTimestamp int64, endTimestamp int64, modelName string, tokenName string, startIdx int, num int, group string, requestId string, upstreamRequestId string) (logs []*Log, total int64, err error) {
	var tx *gorm.DB
	if logType == LogTypeUnknown {
		tx = LOG_DB.Where("logs.user_id = ?", userId)
	} else {
		tx = LOG_DB.Where("logs.user_id = ? and logs.type = ?", userId, logType)
	}

	if tx, err = applyExplicitLogTextFilter(tx, "logs.model_name", modelName); err != nil {
		return nil, 0, err
	}
	if tokenName != "" {
		tx = tx.Where("logs.token_name = ?", tokenName)
	}
	if requestId != "" {
		tx = tx.Where("logs.request_id = ?", requestId)
	}
	if upstreamRequestId != "" {
		tx = tx.Where("logs.upstream_request_id = ?", upstreamRequestId)
	}
	if startTimestamp != 0 {
		tx = tx.Where("logs.created_at >= ?", startTimestamp)
	}
	if endTimestamp != 0 {
		tx = tx.Where("logs.created_at <= ?", endTimestamp)
	}
	if group != "" {
		tx = tx.Where("logs."+logGroupCol+" = ?", group)
	}
	err = tx.Model(&Log{}).Limit(logSearchCountLimit).Count(&total).Error
	if err != nil {
		common.SysError("failed to count user logs: " + err.Error())
		return nil, 0, errors.New("查询日志失败")
	}
	order := "logs.id desc"
	if common.UsingLogDatabase(common.DatabaseTypeClickHouse) {
		order = clickHouseLogOrder("logs.")
	}
	err = tx.Order(order).Limit(num).Offset(startIdx).Find(&logs).Error
	if err != nil {
		common.SysError("failed to search user logs: " + err.Error())
		return nil, 0, errors.New("查询日志失败")
	}

	formatUserLogs(logs, startIdx)
	return logs, total, err
}

func CountOldLog(ctx context.Context, targetTimestamp int64) (int64, error) {
	var total int64
	if err := LOG_DB.WithContext(ctx).Model(&Log{}).Where("created_at < ?", targetTimestamp).Count(&total).Error; err != nil {
		return 0, err
	}
	return total, nil
}

func DeleteOldLogBatch(ctx context.Context, targetTimestamp int64, limit int) (int64, error) {
	if limit <= 0 {
		limit = 100
	}
	if nil != ctx.Err() {
		return 0, ctx.Err()
	}

	if common.UsingLogDatabase(common.DatabaseTypeClickHouse) {
		// ClickHouse DELETE is a heavy mutation that rewrites data parts, so
		// per-batch mutations would be pathologically slow. Remove all matching
		// rows in a single synchronous mutation regardless of limit; the reported
		// count lets the caller's progress loop complete in one pass.
		total, err := CountOldLog(ctx, targetTimestamp)
		if err != nil {
			return 0, err
		}
		if total == 0 {
			return 0, nil
		}
		if err := LOG_DB.WithContext(ctx).Exec(
			"ALTER TABLE logs DELETE WHERE created_at < ? SETTINGS mutations_sync = 1",
			targetTimestamp,
		).Error; err != nil {
			return 0, err
		}
		return total, nil
	}

	result := LOG_DB.WithContext(ctx).Where("created_at < ?", targetTimestamp).Limit(limit).Delete(&Log{})
	if nil != result.Error {
		return 0, result.Error
	}
	return result.RowsAffected, nil
}
